func hdr(pairs ...string) http.Header {
	h := http.Header{}
	for i := 0; i+1 < len(pairs); i += 2 {
		h.Add(pairs[i], pairs[i+1])
	}
	return h
}

func hasVendor(w []model.WAFDetection, vendor string) bool {
	for _, d := range w {
		if d.Vendor == vendor {
			return true
		}
	}
	return false
}

